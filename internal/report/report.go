// Package report renders merged findings into human-readable reports.
package report

import (
	"fmt"
	"io"
	"sort"
	"strings"

	"github.com/blocktack/blocktack/internal/core"
)

// Markdown writes a findings report grouped by severity, most severe first.
func Markdown(w io.Writer, findings []core.Finding, title string) error {
	fs := make([]core.Finding, len(findings))
	copy(fs, findings)
	sort.SliceStable(fs, func(i, j int) bool {
		ri, rj := core.SeverityRank(fs[i].Severity), core.SeverityRank(fs[j].Severity)
		if ri != rj {
			return ri > rj
		}
		return fs[i].Layer < fs[j].Layer
	})

	fmt.Fprintf(w, "# %s\n\n", title)
	fmt.Fprintf(w, "**%d findings** — generated by BlockTack\n\n", len(fs))

	counts := map[core.Severity]int{}
	for _, f := range fs {
		counts[core.NormalizeSeverity(f.Severity)]++
	}
	seenCounts := false
	for _, s := range []core.Severity{core.SevCritical, core.SevHigh, core.SevMedium, core.SevLow, core.SevInfo} {
		if counts[s] > 0 {
			fmt.Fprintf(w, "- **%s**: %d\n", s, counts[s])
			seenCounts = true
		}
	}
	if seenCounts {
		fmt.Fprintln(w)
	}

	current := core.Severity("(none)")
	for _, f := range fs {
		if f.Severity != current {
			current = f.Severity
			fmt.Fprintf(w, "## %s\n\n", strings.ToUpper(string(current)))
		}
		fmt.Fprintf(w, "### %s\n\n", f.Title)
		fmt.Fprintf(w, "- **ID**: %s\n", f.ID)
		fmt.Fprintf(w, "- **Layer**: %s\n", f.Layer)
		fmt.Fprintf(w, "- **Weakness**: %s\n", f.Weakness)
		fmt.Fprintf(w, "- **Source**: %s\n", f.Source)
		if f.Target != "" {
			fmt.Fprintf(w, "- **Target**: %s\n", f.Target)
		}
		fmt.Fprintf(w, "- **Confidence**: %s\n\n", f.Confidence)
		if f.Description != "" {
			fmt.Fprintf(w, "%s\n\n", f.Description)
		}
		if f.Evidence != "" {
			fmt.Fprintf(w, "> Evidence: `%s`\n\n", f.Evidence)
		}
		if f.PoC != "" {
			fmt.Fprintf(w, "**PoC**: `%s`\n\n", f.PoC)
		}
	}
	return nil
}
